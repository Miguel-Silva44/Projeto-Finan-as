CREATE TABLE app_user (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(100) NOT NULL, email VARCHAR(200) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL, verified BOOLEAN NOT NULL DEFAULT FALSE,
 timezone VARCHAR(80) NOT NULL DEFAULT 'America/Sao_Paulo', deleted_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE access_token (
 hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 purpose VARCHAR(12) NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE account (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 name VARCHAR(100) NOT NULL, kind VARCHAR(20) NOT NULL CHECK(kind IN ('CORRENTE','POUPANCA','CARTEIRA')),
 opening BIGINT NOT NULL CHECK(opening BETWEEN -999999999999 AND 999999999999), reference_date DATE NOT NULL,
 archived BOOLEAN NOT NULL DEFAULT FALSE, version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id)
);
CREATE TABLE category (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 name VARCHAR(100) NOT NULL, kind VARCHAR(10) NOT NULL CHECK(kind IN ('RECEITA','DESPESA')),
 archived BOOLEAN NOT NULL DEFAULT FALSE, version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id)
);
CREATE TABLE recurrence (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 account_id VARCHAR(36) NOT NULL, category_id VARCHAR(36) NOT NULL, kind VARCHAR(10) NOT NULL CHECK(kind IN ('RECEITA','DESPESA')),
 description VARCHAR(200) NOT NULL, amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 999999999999), anchor_day INT NOT NULL CHECK(anchor_day BETWEEN 1 AND 31),
 start_date DATE NOT NULL, end_date DATE, active BOOLEAN NOT NULL DEFAULT TRUE, version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id), FOREIGN KEY(account_id,user_id) REFERENCES account(id,user_id), FOREIGN KEY(category_id,user_id) REFERENCES category(id,user_id)
);
CREATE TABLE entry (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 account_id VARCHAR(36) NOT NULL, category_id VARCHAR(36) NOT NULL, recurrence_id VARCHAR(36), occurrence_month VARCHAR(7),
 description VARCHAR(200) NOT NULL, kind VARCHAR(10) NOT NULL CHECK(kind IN ('RECEITA','DESPESA')),
 amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 999999999999), competence DATE NOT NULL, due_date DATE NOT NULL, realized_date DATE,
 status VARCHAR(10) NOT NULL CHECK(status IN ('PENDENTE','REALIZADO','CANCELADO')), version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id), UNIQUE(recurrence_id,occurrence_month),
 CHECK((status='REALIZADO' AND realized_date IS NOT NULL) OR (status<>'REALIZADO' AND realized_date IS NULL)),
 FOREIGN KEY(account_id,user_id) REFERENCES account(id,user_id), FOREIGN KEY(category_id,user_id) REFERENCES category(id,user_id), FOREIGN KEY(recurrence_id,user_id) REFERENCES recurrence(id,user_id)
);
CREATE TABLE transfer (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 source_id VARCHAR(36) NOT NULL, destination_id VARCHAR(36) NOT NULL, amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 999999999999),
 effective_date DATE NOT NULL, status VARCHAR(10) NOT NULL DEFAULT 'REALIZADO' CHECK(status IN ('REALIZADO','CANCELADO')), version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(source_id<>destination_id), FOREIGN KEY(source_id,user_id) REFERENCES account(id,user_id), FOREIGN KEY(destination_id,user_id) REFERENCES account(id,user_id)
);
CREATE TABLE card (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 name VARCHAR(100) NOT NULL, credit_limit BIGINT NOT NULL CHECK(credit_limit BETWEEN 1 AND 999999999999),
 closing_day INT NOT NULL CHECK(closing_day BETWEEN 1 AND 31), due_day INT NOT NULL CHECK(due_day BETWEEN 1 AND 31),
 archived BOOLEAN NOT NULL DEFAULT FALSE, version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(id,user_id)
);
CREATE TABLE invoice (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 card_id VARCHAR(36) NOT NULL, month VARCHAR(7) NOT NULL, closing_date DATE NOT NULL, due_date DATE NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'ABERTA' CHECK(status IN ('ABERTA','FECHADA','PAGA')), manual_reopen BOOLEAN NOT NULL DEFAULT FALSE, version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id), UNIQUE(card_id,month), FOREIGN KEY(card_id,user_id) REFERENCES card(id,user_id)
);
CREATE TABLE purchase (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 card_id VARCHAR(36) NOT NULL, category_id VARCHAR(36) NOT NULL, description VARCHAR(200) NOT NULL, purchase_date DATE NOT NULL,
 amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 999999999999), installments INT NOT NULL CHECK(installments BETWEEN 1 AND 120),
 status VARCHAR(10) NOT NULL DEFAULT 'ATIVA' CHECK(status IN ('ATIVA','CANCELADA')), version INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(id,user_id), FOREIGN KEY(card_id,user_id) REFERENCES card(id,user_id), FOREIGN KEY(category_id,user_id) REFERENCES category(id,user_id)
);
CREATE TABLE installment (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 purchase_id VARCHAR(36) NOT NULL, invoice_id VARCHAR(36) NOT NULL, number INT NOT NULL, amount BIGINT NOT NULL CHECK(amount>0),
 UNIQUE(purchase_id,number), FOREIGN KEY(purchase_id,user_id) REFERENCES purchase(id,user_id), FOREIGN KEY(invoice_id,user_id) REFERENCES invoice(id,user_id)
);
CREATE TABLE invoice_payment (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 invoice_id VARCHAR(36) NOT NULL, account_id VARCHAR(36) NOT NULL, amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 999999999999), effective_date DATE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, active_invoice VARCHAR(36) UNIQUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id,user_id) REFERENCES invoice(id,user_id), FOREIGN KEY(account_id,user_id) REFERENCES account(id,user_id)
);
CREATE TABLE budget (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 category_id VARCHAR(36) NOT NULL, month VARCHAR(7) NOT NULL, amount BIGINT NOT NULL CHECK(amount BETWEEN 1 AND 999999999999), version INT NOT NULL DEFAULT 0,
 UNIQUE(user_id,category_id,month), FOREIGN KEY(category_id,user_id) REFERENCES category(id,user_id)
);
CREATE TABLE audit (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
 entity VARCHAR(30) NOT NULL, entity_id VARCHAR(36) NOT NULL, action VARCHAR(40) NOT NULL,
 before_value TEXT NOT NULL, after_value TEXT NOT NULL, reason VARCHAR(300), created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE idempotency (
 user_id VARCHAR(36) NOT NULL REFERENCES app_user(id) ON DELETE CASCADE, operation_key VARCHAR(36) NOT NULL,
 operation VARCHAR(80) NOT NULL, request_hash VARCHAR(64) NOT NULL, result VARCHAR(100) NOT NULL,
 PRIMARY KEY(user_id,operation_key)
);
CREATE INDEX entry_owner_dates ON entry(user_id,competence,due_date);
CREATE INDEX entry_account ON entry(account_id,status,realized_date);
CREATE INDEX invoice_owner ON invoice(user_id,due_date);
CREATE INDEX audit_owner ON audit(user_id,created_at);
